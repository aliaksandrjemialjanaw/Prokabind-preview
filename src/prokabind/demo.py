"""Допуск белка к показу до фиксации (SPEC п. 5.8; `CONTRACTS.md` § 4.7).

Без PyTorch: проверка — членство в множестве.
"""


def eligible(protein, b6_inputs):
    """Белок допустим для показа до фиксации, только если его данные не входят ни во вход, ни в фон Б6
    (SPEC п. 5.8, тест 12 п. 4.11: «пересечение с входами Б6 должно быть пустым»).

    `b6_inputs` — ключи белков, чьи пики служат Б6 единицей или фоном (п. 3.8). Остальные условия
    п. 5.8 — набор показа и родство показанного белка — живут в проверках задач T16 и T27: они требуют
    данных, которых у этой функции нет (`CONTRACTS.md` § 3.0.1).
    """
    return str(protein) not in set(b6_inputs)
