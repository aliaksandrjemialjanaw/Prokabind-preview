"""Семейство белка — объединение меток Pfam внутри групп родства (SPEC п. 3.6, п. 1.5).

Сигнатура и правило — строка `family_labels` `CONTRACTS.md` § 4.8; вход — столбец `pfam` таблицы белков
(§ 2.3) и столбец `relatedness_group` разбиения (§ 2.6). Правило **одно** на обучение и оценку: дорожка
«чужой белок» (SPEC п. 4.5) зовёт его отсюда, а `work/lib/eval_defs.py` этот модуль импортирует, а не
повторяет (§ 4.3). Без PyTorch и без NumPy: код оценки работает системным Python.

Правило SPEC п. 3.6 дословно: «Метки, которые встречаются вместе в одной группе родства, объединяются,
и объединение идёт по цепочке.» Три записанных ограничения — ниже, каждое у своего места в коде.

Вход правила — **одна метка на белок** (SPEC п. 3.6: «Вход правила — одна метка на белок: сильнейший
ДНК-связывающий домен, а если его нет — сильнейший домен»): первая метка значения белка, потому что
столбец `pfam` упорядочен так, что первой стоит именно она (`CONTRACTS.md` § 2.3). Остальные попадания
в объединение не входят (третий заход T09, 31.10, по аудиту работы сессии спецификации, Н1).
"""

#: Домен-приёмник регуляторов ответа: общий для разных семейств, объединений не создаёт
#: (ограничение 1 SPEC п. 3.6).
RESPONSE_REG = 'Response_reg'

#: Метка «не определено» (SPEC п. 1.5: «Метка „не определено“ в объединение не входит»).
UNDETERMINED = 'undetermined'

# Ограничение 2 SPEC п. 3.6: «метка, ошибочная по самому белку, исправляется у этого белка до
# объединения, поимённо, с доводом». Ключ — sha256 последовательности белка (`CONTRACTS.md` § 1),
# значение — метки белка после исправления. Доводы — SPEC п. 3.6, числа — `work/review/round8_check.out`,
# V4. Имена и локус-теги даны для чтения: правило работает по ключу, потому что имя белка не ключ.
CORRECTIONS = {
    # NagC, Escherichia coli K-12, b0676: самый сильный домен — ROK (344,5 бита, остатки 89–392),
    # а метку MarR белок получил по слабому попаданию 29,0 бита на N-конце; через NagC объединение
    # сшивало семейство MarR с семейством ROK в одно «семейство» из 61 белка.
    '4989fad8d41fd6e7483d7ec8dabcbecede8b7c5692b1a6de8a6bcb1d4113e0df': ('ROK',),
    # Mlc, Escherichia coli K-12, b1594: тот же разбор, ROK (в нынешней таблице метка уже одна —
    # исправление оставлено, потому что список SPEC п. 3.6 называет оба белка).
    'cf9102a4fde8b1a00cf540eb5202eab2fa4609566349784c508fd8d68c01ba17': ('ROK',),
    # SCO4407, Streptomyces coelicolor: есть попадания моделей MarR и MarR_2 выше порога сбора Pfam,
    # а метки HTH_38 и HTH_MmpR5 оставляли семейство MarR разрезанным надвое (описание HTH_MmpR5
    # в Pfam — «MmpR5-like MarR family transcriptional regulator»).
    '934671ba2b8e65ccbf8fd310b02e346234e099992428b469a25619b816c63871': ('MarR',),
    # SCO3632, Streptomyces coelicolor: то же.
    '7d5c29eeab2ede9a49c2d11e0579f0677d8a8177748d4ff1b6e52d061dbd047a': ('MarR',),
}


def _labels(value):
    """Метки белка: список, кортеж или строка через `;` (столбец `pfam` § 2.3). Пусто — нет метки."""
    if value is None:
        return []
    if isinstance(value, str):
        return [x for x in (p.strip() for p in value.split(';')) if x]
    return [x for x in (str(p).strip() for p in value) if x]


def is_other_family(a, b):
    """«Другое семейство» в смысле SPEC п. 1.5 (`CONTRACTS.md` § 4.5): `True` только когда оба
    семейства известны и различны.

    Метка «не определено» семейства не образует (п. 3.6), поэтому «не определено» хотя бы с одной
    стороны даёт `False`: дорожка «чужой белок» требует положительного утверждения «другое
    семейство», а о белке без семейства нельзя сказать ни «то же», ни «другое». Иначе чужим
    отрицательным стал бы сайт белка того же семейства — ровно то, от чего правило защищает
    (записано 31.10 по рецензии кода T09).
    """
    if a is None or b is None:
        return False
    if a == UNDETERMINED or b == UNDETERMINED:
        return False
    return str(a) != str(b)


def family_labels(raw_pfam, groups):
    """Семейство каждого белка по SPEC п. 3.6. `raw_pfam` — белок → его сырые метки Pfam,
    `groups` — белок → его группа родства (≥40%, § 2.6). Ответ — белок → имя семейства
    (метки объединения через `+`, по возрастанию) или `undetermined`.

    Метка белка — **одна: первая метка его значения** (строка через `;` или список), после поимённого
    исправления; остальные метки белка в объединение не входят (`CONTRACTS.md` § 4.8). Вызывающий код
    подаёт столбец `pfam` целиком, первую метку берёт эта функция.

    Объединение идёт по меткам, встретившимся вместе **в одной группе родства**, цепочкой: метки двух
    белков одной группы сливаются, даже если вместе у одного белка их нет, а метки белков разных групп
    сами по себе не сливаются. Перебор идёт по отсортированным ключам: имя семейства не должно зависеть
    от порядка словаря (`CONSTITUTION.md`, ст. 6).
    """
    keys = sorted(raw_pfam)
    # Белок, которого нет в `groups`, — отказ, а не общий «ящик» без группы (`CONTRACTS.md` § 4.8,
    # записано 31.10 по рецензии кода T09): в одном «ящике» метки всех таких белков сшивались бы
    # между собой по цепочке, и семейство зависело бы от того, кого не хватает в разбиении.
    missing = [p for p in keys if p not in groups]
    if missing:
        raise ValueError('белка нет в группах родства (`CONTRACTS.md` § 4.8): %s%s'
                         % (', '.join(x[:12] for x in missing[:3]),
                            ' и ещё %d' % (len(missing) - 3) if len(missing) > 3 else ''))
    raw = {p: _labels(raw_pfam[p]) for p in keys}
    # исправления поимённо — до объединения (ограничение 2); метка белка — первая метка после исправления
    # (`CONTRACTS.md` § 4.8: со всеми метками белка цепочка сшивала 752 белка из 1 106 в одно «семейство»);
    # Response_reg в объединении не участвует (ограничение 1)
    own = {}
    for p in keys:
        fixed = list(CORRECTIONS[p]) if p in CORRECTIONS else raw[p]
        own[p] = [x for x in fixed[:1] if x != RESPONSE_REG]

    # метки группы родства: по ним идёт объединение
    in_group = {}
    for p in keys:
        in_group.setdefault(groups.get(p), set()).update(own[p])

    parent = {x: x for v in own.values() for x in v}

    def root(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    for g in sorted(in_group, key=lambda x: (x is None, str(x))):
        met = sorted(in_group[g])
        for other in met[1:]:
            a, b = root(met[0]), root(other)
            if a != b:
                parent[max(a, b)] = min(a, b)

    members = {}
    for x in sorted(parent):
        members.setdefault(root(x), []).append(x)
    name_of = {}
    for r, group in members.items():
        name = '+'.join(sorted(group))
        for x in group:
            name_of[x] = name

    out = {}
    for p in keys:
        if own[p]:
            out[p] = name_of[own[p][0]]
            continue
        # Ограничение 1 SPEC п. 3.6: «белок с этой меткой берёт ДНК-связывающую метку своей группы,
        # если она в группе одна». Читается буквально — одна метка, а не одно семейство; иначе белок
        # с одним домен-приёмником наследовал бы семейство группы с двумя разными метками.
        group_labels = sorted(in_group.get(groups.get(p), set()))
        if RESPONSE_REG in raw[p] and len(group_labels) == 1:
            out[p] = name_of[group_labels[0]]
        else:
            out[p] = UNDETERMINED
    return out
